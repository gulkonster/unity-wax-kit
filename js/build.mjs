function notices(inputs) {
    // node_modules/@scope/name/lib/x.js -> { dir: node_modules/@scope/name, file }
    const packages = new Map()
    for (const file of inputs) {
        const match = file.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//)
        if (!match) continue
        const info = JSON.parse(readFileSync(join(match[1], 'package.json'), 'utf8'))
        const key = `${info.name}@${info.version}`
        if (!packages.has(key)) packages.set(key, { dir: match[1], info, files: [] })
        packages.get(key).files.push(file)
    }

    const sections = [...packages.values()]
        .sort((a, b) => a.info.name.localeCompare(b.info.name))
        .map(({ dir, info, files }) => {
            const license = typeof info.license === 'string' ? info.license : info.license?.type ?? 'UNKNOWN'
            return `## ${info.name} ${info.version}\n\nLicense: ${license}\n\n\`\`\`\n${licenseText(dir, files, license).trim()}\n\`\`\`\n`
        })

    return [
        '# Third-party notices',
        '',
        'Unity WAX Kit uses the packages below: Newtonsoft.Json in its C# code, and the npm packages inside its WebGL bundle (`Runtime/Plugins/WebGL/waxkit.bundle.jspre`).',
        'Games that ship Unity WAX Kit must include this file (for example on a licenses / credits screen or as a file).',
        '',
        'Generated by `js/build.mjs`; do not edit.',
        '',
        NEWTONSOFT_SECTION,
        ...sections,
    ].join('\n')
}

// The package's license file, else the License section of its README,
// else its source header plus the standard text of its license.
function licenseText(dir, files, license) {
    const names = readdirSync(dir)
    const licenseFile = names.find((name) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(name))
    if (licenseFile) return readFileSync(join(dir, licenseFile), 'utf8')

    const readme = names.find((name) => /^readme(\.md)?$/i.test(name))
    const section = readme && readFileSync(join(dir, readme), 'utf8').match(/^#+ *licen[cs]e\s*\n([\s\S]*?)(?=^#+ |(?![\s\S]))/im)?.[1]
    if (section && /permission is hereby granted|redistribution and use/i.test(section)) return section

    const header = files
        .map((file) => readFileSync(file, 'utf8').match(/^(?:\s*\/\/.*\n)+|^\s*\/\*[\s\S]*?\*\//)?.[0] ?? '')
        .find((comment) => /licen[cs]e/i.test(comment))
    if (license === 'MIT') return `${header ?? ''}\n\n${MIT_TEXT}`
    if (header) return header
    throw new Error(`No license text found for ${dir}`)
}
